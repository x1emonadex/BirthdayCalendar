import 'dart:math';

/// Подбирает цвет аватара для новой записи.
///
/// Раньше новая запись оставалась без цвета, и в календаре под датой
/// появлялась мелкая точка — её почти не видно, особенно в AMOLED-теме.
/// Теперь у каждого нового дня рождения сразу есть свой цвет: точка
/// исчезает, а день рождения узнаётся по кругу, как и у тех записей,
/// где цвет выбрали вручную.
abstract final class AvatarColor {
  const AvatarColor._();

  /// Палитра аватаров: насыщенные, различимые между собой тона.
  ///
  /// Яркость ограничена снизу и сверху: слишком тёмный круг сливается с
  /// фоном календаря, слишком светлый — с белой подписью внутри.
  static const List<int> palette = [
    0xFFE57373, // красный
    0xFFF06292, // розовый
    0xFFBA68C8, // фиолетовый
    0xFF9575CD, // сиреневый
    0xFF7986CB, // индиго
    0xFF64B5F6, // голубой
    0xFF4FC3F7, // бирюзовый
    0xFF4DD0E1, // циан
    0xFF4DB6AC, // бирюзовый тёмный
    0xFF81C784, // зелёный
    0xFFDCE775, // лаймовый
    0xFFFFD54F, // жёлтый
    0xFFFFB74D, // оранжевый
    0xFFA1887F, // коричневый
    0xFF90A4AE, // серо-голубой
  ];

  static final Random _random = Random();

  /// Возвращает цвет из палитры.
  ///
  /// Подряд выпадать может один и тот же — это нормально, список короткий.
  static int random() => palette[_random.nextInt(palette.length)];
}
