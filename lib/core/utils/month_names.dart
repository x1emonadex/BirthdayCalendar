/// Названия месяцев в именительном падеже: «Сентябрь 2026».
///
/// Список один на всё приложение. Раньше он лежал копией в календаре, в
/// выборе месяца и в подписях списка, и копии расходились.
library;

/// Месяцы по порядку, с января.
const List<String> monthNames = [
  'Январь',
  'Февраль',
  'Март',
  'Апрель',
  'Май',
  'Июнь',
  'Июль',
  'Август',
  'Сентябрь',
  'Октябрь',
  'Ноябрь',
  'Декабрь',
];

/// Название месяца по номеру 1..12; пустая строка, если номер вне диапазона.
String monthName(int month) {
  if (month < 1 || month > 12) return '';
  return monthNames[month - 1];
}

/// Заголовок вида «Сентябрь 2026».
String monthTitle(int year, int month) => '${monthName(month)} $year';
